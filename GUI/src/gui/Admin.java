    public void displayTable_rooms() {
        try {
            rs = st.executeQuery("SELECT room_no,room_type,room_status,room_description from rooms");

            DefaultTableModel model = (DefaultTableModel) roomTable.getModel();

            model.setRowCount(0);

            while (rs.next()) {
                Object row[] = {rs.getInt(1), rs.getString(2), rs.getString(3),
                    rs.getString(4)};

                model.addRow(row);
            }

        } catch (HeadlessException | SQLException sqe) {
            JOptionPane.showMessageDialog(null, sqe);
        }
    }

