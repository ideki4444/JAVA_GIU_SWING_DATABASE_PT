    private void loginButtonKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_loginButtonKeyPressed
        // TODO add your handling code here:
        if (evt.getKeyCode() == KeyEvent.VK_ENTER) { //keyy event if nahuman nakag type sa password diritso na click sa enter in keyboard

            String username = usernameLoginTextField.getText(); //getting inputs from username field login
            String password = new String(passwordLoginTextField.getPassword()); /// getting input from userpassword textfield 

            /// codes para sa login 
            try {
                String q = "";

                if (username.length() == 0 || password.length() == 0) {
                    JOptionPane.showMessageDialog(null, "do not leave the fields empty", "ERROR", JOptionPane.ERROR_MESSAGE);
                } else {
                    q = "SELECT * FROM login WHERE user_name=('" + username + "')";
                    rs = st.executeQuery(q);

                    if (rs.next()) {
                        String user = rs.getString("user_name");
                        String pass = rs.getString("user_password");

                        if (user.equals(username) && pass.equals(password)) {
                            JOptionPane.showMessageDialog(null, "successfully logged in");

                            this.setVisible(false);
                            dashboard.setVisible(true);
                            dashboard.pack();
                            dashboard.setLocationRelativeTo(null);

                        } else if (!pass.equals(password)) {
                            JOptionPane.showMessageDialog(null, "password is incorrect");
                        }
                    } else {

                        JOptionPane.showMessageDialog(null, "Account doesn't exist", "ERROR", JOptionPane.ERROR_MESSAGE);
                    }
                }

            } catch (HeadlessException | SQLException sqe) {
                JOptionPane.showMessageDialog(null, sqe);
            }
        }


    }//GEN-LAST:event_loginButtonKeyPressed

